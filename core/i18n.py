def normalizar(codigo: str | None) -> str:
    """Aceita en, pt e pt-br. Qualquer outra coisa volta para o inglês."""
    if not codigo:
        return "en"
    chave = codigo.strip().lower().replace("_", "-")
    return _ALIASES.get(chave, "en")


def traduzir(idioma: str, chave: str, **valores) -> str:
    tabela = _TEXTO[normalizar(idioma)]
    return tabela[chave].format(**valores)


def nome_visivel(idioma: str, nome: str) -> str:
    return _NOS.get(normalizar(idioma), {}).get(nome, nome)
